// Оттенки RAL приблизительные: экран не передаёт цвет металла точно, об этом сказано на странице.

export interface Color {
  code: string;
  name: string;
  hex: string;
  /** Метка для заголовков и ссылок: «RAL 3005», «RR 32» или название фактуры */
  label: string;
}

const ral = (code: string, name: string, hex: string): Color => ({
  code,
  name,
  hex,
  label: `RAL ${code}`,
});
const rr = (code: string, name: string, hex: string): Color => ({
  code: `RR${code}`,
  name,
  hex,
  label: `RR ${code}`,
});
const named = (code: string, name: string, hex: string): Color => ({
  code,
  name,
  hex,
  label: name,
});

